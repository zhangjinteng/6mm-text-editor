import { expect, test, type Page } from '@playwright/test';
import type { Editor } from 'tinymce';
declare global { interface Window { tinymce: { activeEditor: Editor } } }
const box = (page: Page) => page.frameLocator('.tox-edit-area iframe').locator('body > p #group-text');
const preview = (page: Page) => page.frameLocator('iframe[title="文字效果预览"]').locator('body > [data-text-draggable]');
async function open(page: Page, tab: string) {
  await box(page).click();
  await expect(page.locator('.tox-pop:visible [data-mce-name^="textgroup"]')).toHaveCount(0);
  await page.locator('.tox-pop:visible [data-mce-name="textsettings"]').click();
  const d = page.getByRole('dialog', { name: '文字设置', exact: true });
  await d.getByRole('tab', { name: tab, exact: true }).click(); return d;
}
const content = (page: Page) => page.evaluate(() => window.tinymce.activeEditor.getContent());
test.beforeEach(async ({ page }) => {
  await page.goto('/'); await page.waitForFunction(() => window.tinymce?.activeEditor?.initialized);
  await page.evaluate(() => {
    const e = window.tinymce.activeEditor;
    e.setContent('<p><span id="group-text" data-text-draggable="true" style="position:absolute;left:120px;top:90px;width:300px;font-size:24px;line-height:1.5"><strong style="color:#147d64">混合样式</strong>正文<br>第二行</span></p>');
    e.undoManager.clear(); e.undoManager.add();
  });
});
test('样式和排版移入设置，预览隔离，取消与单步撤销保留原文', async ({ page }) => {
  const before = await content(page); let d = await open(page, '样式');
  await expect(d.getByRole('button', { name: '加粗', exact: true })).toHaveAttribute('aria-pressed', 'mixed');
  await d.getByRole('button', { name: '加粗', exact: true }).click();
  await d.getByRole('button', { name: '斜体', exact: true }).click();
  await d.getByRole('button', { name: '下划线', exact: true }).click();
  await d.getByRole('button', { name: '删除线', exact: true }).click();
  await expect(preview(page)).toHaveCSS('font-weight', '700');
  await expect(preview(page)).toHaveCSS('font-style', 'italic');
  await d.getByRole('tab', { name: '排版', exact: true }).click();
  await d.getByRole('group', { name: '文字对齐', exact: true }).getByRole('button', { name: '居中', exact: true }).click();
  await d.getByLabel('行距倍数', { exact: true }).fill('2');
  await d.getByLabel('字间距（px）', { exact: true }).fill('3');
  await expect(preview(page)).toHaveCSS('line-height', '48px');
  await expect(preview(page)).toHaveCSS('letter-spacing', '3px');
  expect(await content(page)).toBe(before);
  await d.getByRole('button', { name: '取消', exact: true }).click(); expect(await content(page)).toBe(before);
  d = await open(page, '样式');
  await d.getByRole('button', { name: '加粗', exact: true }).click();
  await d.getByRole('button', { name: '斜体', exact: true }).click();
  await d.getByRole('tab', { name: '排版', exact: true }).click();
  await d.getByRole('group', { name: '文字对齐', exact: true }).getByRole('button', { name: '右对齐', exact: true }).click();
  await d.getByLabel('行距倍数', { exact: true }).fill('2');
  await d.getByLabel('字间距（px）', { exact: true }).fill('3');
  await page.screenshot({ path: 'screenshots/text-settings-layout.png' });
  await d.getByRole('button', { name: '应用设置', exact: true }).click();
  await expect(box(page)).toHaveCSS('text-align', 'right');
  await expect(box(page)).toHaveCSS('font-style', 'italic');
  await expect(box(page)).toHaveCSS('letter-spacing', '3px');
  await expect(box(page)).toHaveCSS('left', '120px');
  await page.evaluate(() => window.tinymce.activeEditor.undoManager.undo()); expect(await content(page)).toBe(before);
  await page.evaluate(() => window.tinymce.activeEditor.undoManager.redo());
  d = await open(page, '排版'); await expect(d.getByLabel('行距倍数', { exact: true })).toHaveValue('2');
  await d.getByLabel('行距倍数', { exact: true }).fill('8');
  await d.getByRole('button', { name: '应用设置', exact: true }).click();
  await expect(d.getByRole('alert')).toContainText('0.5—5');
});
test('上下标与清除格式可预览撤销，保留文字效果和定位', async ({ page }) => {
  let d = await open(page, '样式');
  await d.getByLabel('上下标', { exact: true }).selectOption('super');
  await expect(preview(page).locator('sup')).toContainText('混合样式');
  await d.getByRole('tab', { name: '外观', exact: true }).click();
  await d.getByLabel('整体不透明度（0—100%）', { exact: true }).fill('60');
  await d.getByRole('button', { name: '应用设置', exact: true }).click();
  await expect(box(page).locator('sup')).toHaveCount(1);
  const formatted = await content(page);
  d = await open(page, '样式'); await expect(d.getByLabel('上下标', { exact: true })).toHaveValue('super');
  await d.getByRole('button', { name: '清除格式', exact: true }).click();
  await expect(preview(page).locator('sup,strong')).toHaveCount(0);
  await expect(preview(page)).toHaveCSS('font-size', '15px');
  await expect(preview(page)).toHaveCSS('opacity', '0.6');
  expect(await content(page)).toBe(formatted);
  await d.getByRole('button', { name: '斜体', exact: true }).click();
  await d.getByRole('button', { name: '应用设置', exact: true }).click();
  await expect(box(page)).toHaveCSS('font-style', 'italic');
  await expect(box(page)).toHaveCSS('opacity', '0.6'); await expect(box(page)).toHaveCSS('left', '120px');
  await page.evaluate(() => window.tinymce.activeEditor.undoManager.undo()); expect(await content(page)).toBe(formatted);
});
test('对象页支持锁定、取消、重新打开解锁，以及复制锁定文字', async ({ page }) => {
  const before = await content(page); let d = await open(page, '对象');
  await d.getByLabel('锁定文本框', { exact: true }).check();
  await d.getByRole('button', { name: '取消', exact: true }).click(); expect(await content(page)).toBe(before);
  d = await open(page, '对象'); await d.getByLabel('锁定文本框', { exact: true }).check();
  await d.getByRole('button', { name: '应用设置', exact: true }).click();
  await expect(box(page)).toHaveAttribute('data-text-locked', 'true');
  d = await open(page, '对象');
  await expect(d.getByRole('tab', { name: '样式', exact: true })).toBeDisabled();
  await expect(d.getByLabel('锁定文本框', { exact: true })).toBeChecked();
  await d.getByRole('button', { name: '创建文字副本', exact: true }).click();
  const copies = page.frameLocator('.tox-edit-area iframe').locator('body > p > [data-text-draggable]');
  await expect(copies).toHaveCount(2); await expect(copies.nth(1)).not.toHaveAttribute('data-text-locked');
  await expect(copies.nth(1).locator('strong')).toHaveCSS('color', 'rgb(20, 125, 100)');
  await page.evaluate(() => window.tinymce.activeEditor.undoManager.undo()); await expect(copies).toHaveCount(1);
  d = await open(page, '对象'); await d.getByLabel('锁定文本框', { exact: true }).uncheck();
  await d.getByRole('button', { name: '应用设置', exact: true }).click();
  await expect(box(page)).not.toHaveAttribute('data-text-locked');
  d = await open(page, '样式'); await expect(d.getByRole('button', { name: '加粗', exact: true })).toBeEnabled();
});
test('九个分类在窄屏可见，键盘可切换，应用并复制保留样式', async ({ page }) => {
  const d = await open(page, '样式');
  await d.getByRole('button', { name: '斜体', exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(d.getByRole('tablist', { name: '文字设置分类', exact: true }).getByRole('tab')).toHaveCount(9);
  await d.getByRole('tab', { name: '样式', exact: true }).press('End');
  await expect(d.getByRole('tab', { name: '对象', exact: true })).toBeFocused();
  expect(await d.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true);
  await page.screenshot({ path: 'screenshots/text-settings-object-mobile.png' });
  await d.getByRole('button', { name: '创建文字副本', exact: true }).click();
  const copies = page.frameLocator('.tox-edit-area iframe').locator('body > p > [data-text-draggable]');
  await expect(copies).toHaveCount(2); await expect(copies.nth(1)).toHaveCSS('font-style', 'italic');
});
