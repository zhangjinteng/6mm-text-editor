import { expect, test, type Page } from '@playwright/test';
const frame = (p: Page) => p.frameLocator('.tox-edit-area iframe');
const panel = (p: Page) => p.getByRole('complementary', { name: '图片配置面板' });
test.beforeEach(async ({ page }) => {
  await page.goto('/'); await page.waitForFunction(() => window.tinymce?.activeEditor?.initialized);
  await page.evaluate(async () => {
    const c = document.createElement('canvas'); c.width = 180; c.height = 100;
    const ctx = c.getContext('2d')!; ctx.fillStyle = '#147d64'; ctx.fillRect(0, 0, 90, 100); ctx.fillStyle = '#f5ad58'; ctx.fillRect(90, 0, 90, 100);
    const e = window.tinymce.activeEditor;
    e.setContent(`<p><img id="a" src="${c.toDataURL()}" style="position:absolute;left:50px;top:50px;width:180px;height:100px"></p><p><img id="b" src="${c.toDataURL()}" style="position:absolute;left:300px;top:50px;width:180px;height:100px"></p><p><span id="words" data-text-draggable="true" style="position:absolute;left:50px;top:230px;font-size:28px">文字配置切换</span></p>`);
    await e.uploadImages(); e.undoManager.clear(); e.undoManager.add();
  });
});
test('图片配置即时生效，切换图片与文字和空白，撤销保留对象独立设置', async ({ page }) => {
  await expect(panel(page)).toBeHidden();
  await frame(page).locator('body > p > #a').click();
  await expect(panel(page)).toBeVisible();
  await expect(page.locator('.tox-pop:visible [data-mce-name="imagesettings"]')).toBeVisible();
  await panel(page).getByLabel('水平翻转', { exact: true }).check();
  await expect(frame(page).locator('#a')).toHaveCSS('scale', '-1 1');
  await panel(page).getByRole('tab', { name: '外观', exact: true }).click();
  await panel(page).getByRole('slider', { name: '不透明度', exact: true }).fill('65');
  await expect(frame(page).locator('#a')).toHaveCSS('opacity', '0.65');
  await frame(page).locator('#b').click();
  await panel(page).getByRole('tab', { name: '外观', exact: true }).click();
  await expect(panel(page).getByRole('slider', { name: '不透明度', exact: true })).toHaveValue('100');
  await panel(page).getByRole('slider', { name: '不透明度', exact: true }).fill('80');
  await expect(frame(page).locator('#b')).toHaveCSS('opacity', '0.8');
  await expect(frame(page).locator('#a')).toHaveCSS('opacity', '0.65');
  await page.evaluate(() => window.tinymce.activeEditor.undoManager.undo());
  await expect(frame(page).locator('#b')).toHaveCSS('opacity', '1');
  await frame(page).locator('#words').click();
  await expect(page.getByRole('complementary', { name: '文字配置面板' })).toBeVisible();
  await expect(panel(page)).toBeHidden();
  await frame(page).locator('#a').click();
  await expect(panel(page)).toBeVisible();
  await expect(page.getByRole('complementary', { name: '文字配置面板' })).toBeHidden();
  await page.screenshot({ path: 'screenshots/image-config-panel-desktop.png' });
  await frame(page).locator('body').click({ position: { x: 550, y: 360 } });
  await expect(panel(page)).toBeHidden();
});
test('图片侧栏支持蒙版滤镜描边和锁定，弹窗隔离预览仍可取消', async ({ page }) => {
  await frame(page).locator('#a').click();
  await panel(page).getByLabel('锁定位置与尺寸', { exact: true }).check();
  await expect(frame(page).locator('#a')).toHaveAttribute('data-image-locked', 'true');
  await panel(page).getByLabel('锁定位置与尺寸', { exact: true }).uncheck();
  await expect(frame(page).locator('#a')).not.toHaveAttribute('data-image-locked');
  await panel(page).getByRole('tab', { name: '蒙版', exact: true }).click();
  await panel(page).getByRole('button', { name: '圆形', exact: true }).click();
  await expect(frame(page).locator('#a')).toHaveCSS('clip-path', /^circle\((closest-side )?at 50% 50%\)$/);
  await panel(page).getByRole('tab', { name: '滤镜', exact: true }).click();
  await panel(page).getByRole('button', { name: '黑白', exact: true }).click();
  await expect(frame(page).locator('#a')).toHaveCSS('filter', /grayscale\(1\)/);
  await panel(page).getByRole('tab', { name: '描边', exact: true }).click();
  await panel(page).getByLabel('启用描边', { exact: true }).check();
  await expect(frame(page).locator('#a')).toHaveAttribute('data-image-stroke-id');
  await frame(page).locator('#a').click();
  await page.locator('.tox-pop:visible [data-mce-name="imagesettings"]').click();
  const d = page.getByRole('dialog', { name: '图片设置', exact: true });
  await d.getByLabel('水平翻转', { exact: true }).check();
  await expect(frame(page).locator('#a')).toHaveCSS('scale', '1');
  await d.getByRole('button', { name: '取消', exact: true }).click();
  await expect(panel(page)).toBeVisible();
  await panel(page).getByRole('button', { name: '重置效果', exact: true }).click();
  await expect(frame(page).locator('#a')).not.toHaveAttribute('data-image-stroke-id');
  await expect(frame(page).locator('#a')).toHaveCSS('clip-path', 'none');
  await page.setViewportSize({ width: 390, height: 844 });
  await panel(page).scrollIntoViewIfNeeded();
  const bounds = (await panel(page).boundingBox())!; expect(bounds.x).toBeGreaterThanOrEqual(0); expect(bounds.width).toBeLessThanOrEqual(390);
  await page.screenshot({ path: 'screenshots/image-config-panel-mobile.png' });
});
test('替换图片先验证来源，失败不改原图；读取中切换对象不会误应用', async ({ page }) => {
  await frame(page).locator('#a').click();
  const before = await frame(page).locator('#a').getAttribute('src');
  await panel(page).getByRole('textbox', { name: '图片地址', exact: true }).fill('javascript:bad');
  await panel(page).getByRole('textbox', { name: '图片地址', exact: true }).press('Tab');
  await expect(panel(page).getByRole('alert')).toContainText('HTTP');
  await expect(frame(page).locator('#a')).toHaveAttribute('src', before!);
  await page.route('**/slow-image.png', async route => {
    await new Promise(resolve => setTimeout(resolve, 500));
    await route.fulfill({ contentType: 'image/png', body: Buffer.from(before!.split(',')[1]!, 'base64') });
  });
  await panel(page).getByRole('textbox', { name: '图片地址', exact: true }).fill('http://localhost:5184/slow-image.png');
  await panel(page).getByRole('textbox', { name: '图片地址', exact: true }).press('Tab');
  await frame(page).locator('#b').click();
  await page.waitForTimeout(650);
  await expect(frame(page).locator('#a')).toHaveAttribute('src', before!);
  await expect(frame(page).locator('#b')).toHaveAttribute('src', before!);
});
