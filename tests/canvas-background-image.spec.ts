import { expect, test } from '@playwright/test';

test('画布侧栏直接选择背景图，支持取消、替换、撤销、保存预览和移除', async ({ page }) => {
  await page.goto('/');
  await page.waitForFunction(() => window.tinymce?.activeEditor?.initialized);
  const sources = await page.evaluate(() => {
    const canvas = document.createElement('canvas'); canvas.width = 80; canvas.height = 40;
    const ctx = canvas.getContext('2d')!;
    ctx.fillStyle = '#a3d9c0'; ctx.fillRect(0, 0, 80, 40); const first = canvas.toDataURL();
    ctx.fillStyle = '#efb366'; ctx.fillRect(0, 0, 80, 40); const second = canvas.toDataURL();
    const editor = window.tinymce.activeEditor;
    editor.setContent(`<p>背景上的正文</p><p><img id="original" src="${first}" width="40" height="20"></p>`);
    editor.undoManager.clear(); editor.undoManager.add();
    return { first, second };
  });
  const panel = page.getByRole('complementary', { name: '画布配置面板' });
  const frame = page.frameLocator('.tox-edit-area iframe');
  const background = frame.locator('img[data-document-background]');
  const dialog = page.getByRole('dialog', { name: '设置画布背景图', exact: true });
  await frame.locator('body').click({ position: { x: 500, y: 350 } });
  await panel.getByRole('tab', { name: '插入', exact: true }).click();
  const button = panel.getByRole('button', { name: '设置画布背景图', exact: true });
  const emojiBox = (await panel.getByRole('button', { name: '表情符号', exact: true }).boundingBox())!;
  expect((await button.boundingBox())!.y).toBeGreaterThan(emojiBox.y + emojiBox.height);
  await button.click();
  await dialog.getByRole('button', { name: '取消', exact: true }).click();
  await expect(background).toHaveCount(0);
  await button.click();
  const chooser = page.waitForEvent('filechooser');
  await dialog.locator('.tox-browse-url').click();
  await (await chooser).setFiles({ name: 'background.png', mimeType: 'image/png', buffer: Buffer.from(sources.first.split(',')[1], 'base64') });
  await expect(dialog.getByRole('combobox', { name: '图片地址', exact: true })).toHaveValue(sources.first);
  await dialog.getByRole('button', { name: '应用背景图', exact: true }).click();
  await expect(background).toHaveCount(1);
  await expect(background).toHaveCSS('object-fit', 'cover');
  await expect(background).toHaveCSS('pointer-events', 'none');
  await expect(frame.locator('#original')).toHaveCount(1);
  await expect(frame.getByText('背景上的正文', { exact: true })).toBeVisible();
  await expect(panel).toBeVisible();
  await button.click();
  await dialog.getByRole('combobox', { name: '图片地址', exact: true }).fill(sources.second);
  await dialog.getByRole('button', { name: '应用背景图', exact: true }).click();
  await expect(background).toHaveCount(1);
  await expect(background).toHaveAttribute('src', sources.second);
  await page.evaluate(() => window.tinymce.activeEditor.undoManager.undo());
  await expect(background).toHaveAttribute('src', sources.first);
  await page.evaluate(() => window.tinymce.activeEditor.undoManager.redo());
  await expect(background).toHaveAttribute('src', sources.second);
  await page.getByRole('button', { name: '保存文档', exact: true }).click();
  await page.reload();
  await page.waitForFunction(() => window.tinymce?.activeEditor?.initialized);
  await expect(background).toHaveAttribute('src', sources.second);
  const views = page.getByRole('navigation', { name: '文档视图' });
  await views.getByRole('button', { name: '预览', exact: true }).click();
  await expect(page.frameLocator('iframe[title="文档预览"]').locator('img[data-document-background]')).toHaveCSS('object-fit', 'cover');
  await views.getByRole('button', { name: '编辑', exact: true }).click();
  await frame.locator('body').click({ position: { x: 500, y: 350 } });
  await panel.getByRole('tab', { name: '插入', exact: true }).click();
  await page.screenshot({ path: 'screenshots/canvas-background-image.png' });
  await button.click();
  await dialog.getByRole('button', { name: '移除背景图', exact: true }).click();
  await expect(background).toHaveCount(0);
  await expect(frame.locator('#original')).toHaveCount(1);
});
