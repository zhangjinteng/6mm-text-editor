import { expect, test, type Page } from '@playwright/test';
const panel = (page: Page) => page.getByRole('complementary', { name: '画布配置面板' });
const frame = (page: Page) => page.frameLocator('.tox-edit-area iframe');
async function blank(page: Page, x = 500, y = 350) {
  await frame(page).locator('body').click({ position: { x, y } });
  await expect(panel(page)).toBeVisible();
}
test.beforeEach(async ({ page }) => {
  await page.goto('/'); await page.waitForFunction(() => window.tinymce?.activeEditor?.initialized);
  await page.evaluate(() => {
    const e = window.tinymce.activeEditor;
    e.setContent('<p><span data-text-draggable="true" id="words" style="position:absolute;left:40px;top:60px;font-size:24px">文字对象</span></p><p><img id="photo" src="data:image/gif;base64,R0lGODlhAQABAIAAAAAAAP///yH5BAEAAAAALAAAAAABAAEAAAIBRAA7" width="100" height="80" style="position:absolute;left:250px;top:60px"></p>');
    e.undoManager.clear(); e.undoManager.add();
  });
});
test('默认显示画布配置，背景即时生效、撤销同步，文字图片配置切换和刷新恢复', async ({ page }) => {
  await expect(panel(page)).toBeVisible();
  const before = await page.evaluate(() => window.tinymce.activeEditor.getContent());
  await blank(page);
  expect(await page.evaluate(() => window.tinymce.activeEditor.getContent())).toBe(before);
  await expect(page.locator('.tox-pop:visible [data-mce-name="canvassettings"]')).toBeVisible();
  await panel(page).getByRole('textbox', { name: '背景颜色', exact: true }).fill('#E03E2D');
  await panel(page).getByRole('textbox', { name: '背景颜色', exact: true }).press('Tab');
  const layer = frame(page).locator('.document-background-color');
  await expect(layer).toHaveCSS('background-color', 'rgb(224, 62, 45)');
  await panel(page).getByRole('slider', { name: '背景透明度', exact: true }).fill('60');
  await expect(layer).toHaveCSS('background-color', 'rgba(224, 62, 45, 0.4)');
  await expect(frame(page).locator('#words')).toHaveCSS('opacity', '1');
  await page.evaluate(() => window.tinymce.activeEditor.undoManager.undo());
  await expect(panel(page)).toBeVisible();
  await expect(panel(page).getByRole('slider')).toHaveValue('0');
  await page.evaluate(() => window.tinymce.activeEditor.undoManager.redo());
  await expect(panel(page).getByRole('slider')).toHaveValue('60');
  await frame(page).locator('#words').click();
  await expect(panel(page)).toBeHidden();
  await expect(page.getByRole('complementary', { name: '文字配置面板' })).toBeVisible();
  await blank(page);
  await expect(page.getByRole('complementary', { name: '文字配置面板' })).toBeHidden();
  await frame(page).locator('#photo').click();
  await expect(panel(page)).toBeHidden();
  await expect(page.getByRole('complementary', { name: '图片配置面板' })).toBeVisible();
  await blank(page);
  await expect(page.getByRole('complementary', { name: '图片配置面板' })).toBeHidden();
  await page.screenshot({ path: 'screenshots/canvas-config-panel-desktop.png' });
  await panel(page).getByRole('button', { name: '收起画布配置' }).click();
  await expect(panel(page)).toBeHidden(); await blank(page);
  await panel(page).getByRole('button', { name: '清除背景颜色' }).click();
  await expect(layer).toHaveCount(0);
  await page.getByRole('navigation', { name: '文档视图' }).getByRole('button', { name: 'HTML', exact: true }).click();
  await expect(panel(page)).toBeHidden();
  await page.reload(); await page.waitForFunction(() => window.tinymce?.activeEditor?.initialized);
  await expect(panel(page)).toBeVisible();
  await expect(panel(page).getByRole('tab', { name: '背景', exact: true })).toHaveAttribute('aria-selected', 'true');
});
test('侧栏插入与弹窗取消互不干扰，输入校验和窄屏布局', async ({ page }) => {
  await blank(page);
  await panel(page).getByRole('textbox', { name: '背景颜色', exact: true }).fill('bad');
  await panel(page).getByRole('textbox', { name: '背景颜色', exact: true }).press('Tab');
  await expect(panel(page).getByRole('alert')).toBeVisible();
  await expect(frame(page).locator('.document-background-color')).toHaveCount(0);
  await panel(page).getByRole('textbox', { name: '背景颜色', exact: true }).fill('#123456');
  await panel(page).getByRole('textbox', { name: '背景颜色', exact: true }).press('Tab');
  await blank(page); await page.locator('.tox-pop:visible [data-mce-name="canvassettings"]').click();
  const dialog = page.getByRole('dialog', { name: '画布设置', exact: true });
  await dialog.getByRole('textbox', { name: '背景颜色', exact: true }).fill('#ffffff');
  await dialog.getByRole('button', { name: '取消', exact: true }).click();
  await expect(panel(page).getByRole('textbox', { name: '背景颜色', exact: true })).toHaveValue('#123456');
  await panel(page).getByRole('tab', { name: '插入', exact: true }).click();
  await panel(page).getByRole('button', { name: '插入文字', exact: true }).click();
  const text = page.getByRole('dialog', { name: '插入文字', exact: true });
  await text.getByRole('textbox', { name: '文本内容' }).fill('侧栏文字');
  await text.getByRole('button', { name: '插入', exact: true }).click();
  await expect(frame(page).getByText('侧栏文字', { exact: true })).toBeVisible();
  await expect(panel(page)).toBeHidden();
  await blank(page, 300, 350);
  await panel(page).getByRole('button', { name: '插入图片', exact: true }).click();
  const image = page.getByRole('dialog').filter({ has: page.getByRole('combobox', { name: '地址', exact: true }) });
  await expect(image.getByRole('combobox', { name: '地址', exact: true })).toHaveValue('');
  await image.getByRole('button', { name: '取消', exact: true }).click();
  await panel(page).getByRole('button', { name: '表情符号', exact: true }).click();
  await expect(page.getByRole('dialog').getByRole('textbox', { name: '搜索', exact: true })).toBeVisible();
  await page.keyboard.press('Escape');
  await page.setViewportSize({ width: 390, height: 844 }); await panel(page).scrollIntoViewIfNeeded();
  const bounds = (await panel(page).boundingBox())!;
  expect(bounds.x).toBeGreaterThanOrEqual(0); expect(bounds.width).toBeLessThanOrEqual(390);
  await page.screenshot({ path: 'screenshots/canvas-config-panel-mobile.png' });
});
test('图片选中后调整画布并撤销，侧栏插入新图片不替换原图', async ({ page }) => {
  await frame(page).locator('#photo').click(); await blank(page);
  await panel(page).getByRole('slider').fill('50');
  await page.evaluate(() => window.tinymce.activeEditor.undoManager.undo());
  await expect(panel(page)).toBeVisible();
  await expect(page.getByRole('complementary', { name: '图片配置面板' })).toBeHidden();
  await panel(page).getByRole('tab', { name: '插入', exact: true }).click();
  await panel(page).getByRole('button', { name: '插入图片', exact: true }).click();
  const d = page.getByRole('dialog').filter({ has: page.getByRole('combobox', { name: '地址', exact: true }) });
  await d.getByRole('combobox', { name: '地址', exact: true }).fill('data:image/gif;base64,R0lGODlhAQABAIAAAAAAAP///yH5BAEAAAAALAAAAAABAAEAAAIBRAA7');
  await d.getByRole('textbox', { name: '替代描述', exact: true }).fill('侧栏新图');
  await d.getByRole('button', { name: '保存', exact: true }).click();
  await expect(frame(page).locator('img')).toHaveCount(2);
  await expect(frame(page).locator('#photo')).toHaveCount(1);
  await expect(page.getByRole('complementary', { name: '图片配置面板' })).toBeVisible();
  await expect(panel(page)).toBeHidden();
});
